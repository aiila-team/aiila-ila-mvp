def load_entities(session, records: list) -> set:
    """Insert entities. Returns set of inserted entity IDs."""
    log(f"Loading {len(records)} entities...")
    inserted_ids = set()
    for i in range(0, len(records), BATCH_SIZE):
        batch = records[i : i + BATCH_SIZE]
        for r in batch:
            # Strip internal helper fields that don't exist in the model
            entity = Entity(
                id=r["id"],
                entity_type=r["entity_type"],
                primary_identifier=r["primary_identifier"],
                display_name=r.get("display_name"),
                risk_score=r.get("risk_score", 0.0),
                risk_level=r.get("risk_level", "low"),
                influence_score=r.get("influence_score", 0.0),
                anomaly_score=r.get("anomaly_score", 0.0),
                sentiment_avg=r.get("sentiment_avg", 0.0),
                event_count=r.get("event_count", 0),
                first_seen=parse_dt(r.get("first_seen")),
                last_seen=parse_dt(r.get("last_seen")),
                is_flagged=r.get("is_flagged", False),
                investigation_notes=r.get("investigation_notes"),
                risk_factors=r.get("risk_factors", []),
                metadata_=r.get("metadata_", {}),
            )
            session.merge(entity)
            inserted_ids.add(r["id"])
        session.flush()
        log(f"   ... {min(i + BATCH_SIZE, len(records))}/{len(records)} entities")
    log(f"   ✓ {len(records)} entities loaded")
    return inserted_ids



# ── Config ────────────────────────────────────────────────────────────────────
DATABASE_URL = os.environ.get(
    "DATABASE_URL",
    "postgresql://ila_user:ila_password123@localhost:5432/ila_db"
)
MOCK_DATA_PATH = Path(__file__).parent / "mock_data.json"
RESET = os.environ.get("RESET", "false").lower() == "true"

BATCH_SIZE = 100   # insert in batches to avoid memory issues


# ── Helpers ───────────────────────────────────────────────────────────────────

def parse_dt(s):
    """Parse ISO datetime string, return None if falsy."""
    if not s:
        return None
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def log(msg: str):
    """Simple timestamped logger."""
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    print(f"[{ts}] {msg}")


def batch_insert(session, model, records: list, batch_size: int = BATCH_SIZE):
    """Insert records in batches, return count inserted."""
    total = 0
    for i in range(0, len(records), batch_size):
        batch = records[i : i + batch_size]
        session.bulk_save_objects([model(**r) for r in batch])
        session.flush()
        total += len(batch)
    return total


# ── Table Setup ───────────────────────────────────────────────────────────────

def setup_tables(engine, reset: bool = False):
    """Create tables (or drop+recreate if RESET=true)."""
    if reset:
        log("⚠️  RESET=true — dropping all tables...")
        Base.metadata.drop_all(engine)
        log("   Tables dropped.")
    log("Creating tables (if not exist)...")
    Base.metadata.create_all(engine)
    log("   Tables ready.")


# ── Loaders ───────────────────────────────────────────────────────────────────

def load_users(session, records: list) -> dict:
    """Insert users. Returns {username → id} map."""
    log(f"Loading {len(records)} users...")
    id_map = {}
    for r in records:
        user = User(
            id=r["id"],
            username=r["username"],
            email=r["email"],
            hashed_password=r["hashed_password"],
            full_name=r.get("full_name"),
            role=r.get("role", "analyst"),
            is_active=r.get("is_active", True),
        )
        session.merge(user)   # merge = insert or update
        id_map[r["username"]] = r["id"]
    session.flush()
    log(f"   ✓ {len(records)} users loaded")
    return id_map


def load_sources(session, records: list) -> dict:
    """Insert data sources. Returns {name → id} map."""
    log(f"Loading {len(records)} sources...")
    id_map = {}
    for r in records:
        src = Source(
            id=r["id"],
            name=r["name"],
            source_type=r["source_type"],
            tier=r["tier"],
            url=r.get("url"),
            description=r.get("description"),
            is_active=r.get("is_active", True),
            reliability_multiplier=r.get("reliability_multiplier", 1.0),
            crawl_interval_minutes=r.get("crawl_interval_minutes", 15),
            last_crawled_at=parse_dt(r.get("last_crawled_at")),
            event_count_today=r.get("event_count_today", 0),
        )
        session.merge(src)
        id_map[r["name"]] = r["id"]
    session.flush()
    log(f"   ✓ {len(records)} sources loaded")
    return id_map


def load_keywords(session, records: list) -> dict:
    """Insert keywords. Returns {word → id} map."""

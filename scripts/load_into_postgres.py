"""
ILA — PostgreSQL Loader
scripts/load_into_postgres.py

Reads the mock_data.json generated by generate_mock_data.py and inserts
everything into PostgreSQL using SQLAlchemy (same ORM the app uses).

Flow:
  1. Read mock_data.json
  2. Create all tables (if not exist)
  3. Insert in dependency order:
       users → sources → keywords → entities → aliases → events → entity_events → alerts

Usage:
  # Make sure PostgreSQL is running (docker compose up postgres)
  python scripts/load_into_postgres.py

  # Or with a custom DB URL:
  DATABASE_URL=postgresql://user:pass@localhost:5432/ila_db python scripts/load_into_postgres.py

  # Reset and reload (drops all data first):
  RESET=true python scripts/load_into_postgres.py
"""


# ── Verification ──────────────────────────────────────────────────────────────

def verify_load(session):
    """Run quick count queries to verify everything loaded."""
    log("\n📊 Load verification:")
    checks = [
        ("users",          "SELECT COUNT(*) FROM users"),
        ("sources",        "SELECT COUNT(*) FROM sources"),
        ("keywords",       "SELECT COUNT(*) FROM keywords"),
        ("entities",       "SELECT COUNT(*) FROM entities"),
        ("entity_aliases", "SELECT COUNT(*) FROM entity_aliases"),
        ("raw_events",     "SELECT COUNT(*) FROM raw_events"),
        ("entity_events",  "SELECT COUNT(*) FROM entity_events"),
        ("risk_alerts",    "SELECT COUNT(*) FROM risk_alerts"),
    ]
    for label, sql in checks:
        count = session.execute(text(sql)).scalar()
        status = "✓" if count > 0 else "⚠️"
        log(f"   {status} {label:20s}: {count:>5} rows")

    # Spot-check: highest risk entity
    result = session.execute(text(
        "SELECT primary_identifier, risk_score, risk_level FROM entities ORDER BY risk_score DESC LIMIT 1"
    )).fetchone()
    if result:
        log(f"\n   🔴 Highest-risk entity: {result[0]} | score={result[1]} | level={result[2]}")

    # Spot-check: alert type distribution
    result = session.execute(text(
        "SELECT alert_type, COUNT(*) FROM risk_alerts GROUP BY alert_type ORDER BY COUNT(*) DESC"
    )).fetchall()
    log("\n   Alert type distribution:")
    for row in result:
        log(f"     {row[0]:30s}: {row[1]}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    log("=" * 60)
    log("ILA Mock Data Loader")
    log("=" * 60)
    log(f"Database: {DATABASE_URL.split('@')[-1]}")  # hide credentials
    log(f"Data file: {MOCK_DATA_PATH}")
    log(f"Reset mode: {RESET}")
    log("")

    # Read mock data
    if not MOCK_DATA_PATH.exists():
        log("❌ mock_data.json not found!")
        log("   Run: python scripts/generate_mock_data.py first")
        sys.exit(1)

    log(f"Reading {MOCK_DATA_PATH.name}...")
    with open(MOCK_DATA_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    meta = data.get("meta", {})
    log(f"   Generated at: {meta.get('generated_at', 'unknown')}")
    for k, v in meta.get("counts", {}).items():
        log(f"   {k:12s}: {v}")
    log("")

    # Connect to DB
    log("Connecting to PostgreSQL...")
    engine = create_engine(
        DATABASE_URL,
        pool_pre_ping=True,
        echo=False,           # set True to see SQL
    )
    Session = sessionmaker(bind=engine)

    # Setup tables
    setup_tables(engine, reset=RESET)

    # Load data in dependency order
    log("\n📥 Loading data...")
    with Session() as session:
        try:
            load_users(session,    data.get("users",    []))
            load_sources(session,  data.get("sources",  []))
            load_keywords(session, data.get("keywords", []))
            load_entities(session, data.get("entities", []))
            load_aliases(session,  data.get("aliases",  []))
            load_events(session,   data.get("events",   []))
            load_alerts(session,   data.get("alerts",   []))

            log("\n💾 Committing transaction...")
            session.commit()
            log("   ✓ Committed!")

            verify_load(session)

        except Exception as e:
            log(f"\n❌ Error during load: {e}")
            session.rollback()
            raise

    log("\n" + "=" * 60)
    log("✅ Mock data loaded successfully!")
    log("   You can now start the FastAPI server and see data.")
    log("=" * 60)


if __name__ == "__main__":
    main()

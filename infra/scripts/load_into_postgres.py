def load_entities(session, records: list) -> set:
    """Insert entities. Returns set of inserted entity IDs."""
    log(f"Loading {len(records)} entities...")
    inserted_ids = set()
    for i in range(0, len(records), BATCH_SIZE):
        batch = records[i : i + BATCH_SIZE]
        for r in batch:
            # Strip internal helper fields that don't exist in the model
            entity = Entity(
                id=r["id"],
                entity_type=r["entity_type"],
                primary_identifier=r["primary_identifier"],
                display_name=r.get("display_name"),
                risk_score=r.get("risk_score", 0.0),
                risk_level=r.get("risk_level", "low"),
                influence_score=r.get("influence_score", 0.0),
                anomaly_score=r.get("anomaly_score", 0.0),
                sentiment_avg=r.get("sentiment_avg", 0.0),
                event_count=r.get("event_count", 0),
                first_seen=parse_dt(r.get("first_seen")),
                last_seen=parse_dt(r.get("last_seen")),
                is_flagged=r.get("is_flagged", False),
                investigation_notes=r.get("investigation_notes"),
                risk_factors=r.get("risk_factors", []),
                metadata_=r.get("metadata_", {}),
            )
            session.merge(entity)
            inserted_ids.add(r["id"])
        session.flush()
        log(f"   ... {min(i + BATCH_SIZE, len(records))}/{len(records)} entities")
    log(f"   ✓ {len(records)} entities loaded")
    return inserted_ids


def load_aliases(session, records: list):
    """Insert entity aliases."""
    log(f"Loading {len(records)} entity aliases...")
    entity_ids = {r["entity_id"] for r in records}
    alias_values = {r["alias_value"] for r in records}
    
    existing_aliases = set()
    if records:
        existing_rows = (
            session.query(EntityAlias.entity_id, EntityAlias.alias_value)
            .filter(EntityAlias.entity_id.in_(list(entity_ids)))
            .filter(EntityAlias.alias_value.in_(list(alias_values)))
            .all()
        )
        existing_aliases = {(row[0], row[1]) for row in existing_rows}

    inserted_count = 0
    updated_count = 0
    
    for i in range(0, len(records), BATCH_SIZE):
        batch = records[i : i + BATCH_SIZE]
        for r in batch:
            if (r["entity_id"], r["alias_value"]) in existing_aliases:
                existing = session.query(EntityAlias).filter(
                    EntityAlias.entity_id == r["entity_id"],
                    EntityAlias.alias_value == r["alias_value"]
                ).first()
                if existing:
                    existing.alias_type = r["alias_type"]
                    existing.platform = r.get("platform")
                    existing.confidence = r.get("confidence", 1.0)
                    existing.resolution_method = r.get("resolution_method", "exact")
                    existing.is_verified = r.get("is_verified", False)
                    updated_count += 1
            else:
                alias = EntityAlias(
                    id=r["id"],
                    entity_id=r["entity_id"],
                    alias_type=r["alias_type"],
                    alias_value=r["alias_value"],
                    platform=r.get("platform"),
                    confidence=r.get("confidence", 1.0),
                    resolution_method=r.get("resolution_method", "exact"),
                    is_verified=r.get("is_verified", False),
                )
                session.merge(alias)
                inserted_count += 1
        session.flush()
    log(f"   ✓ {inserted_count} aliases loaded + {updated_count} aliases updated")


def load_events(session, records: list) -> dict:
    """
    Insert raw events.
    Also builds entity_events (the many-to-many link) from extracted_entities
    and the _person_entity_id helper field in mock data.

    Returns {event_id → entity_id} map for alert linking.
    """
    log(f"Loading {len(records)} raw events...")
    entity_event_records = []

    for i in range(0, len(records), BATCH_SIZE):
        batch = records[i : i + BATCH_SIZE]
        for r in batch:
            # Strip helper fields without mutating the original record.
            person_entity_id = r.get("_person_entity_id")

            event = RawEvent(
                id=r["id"],
                source_id=r["source_id"],
                external_id=r.get("external_id"),
                content=r["content"],
                content_language=r.get("content_language", "unknown"),
                translated_content=r.get("translated_content"),
                url=r.get("url"),
                author_handle=r.get("author_handle"),
                platform=r.get("platform"),
                published_at=parse_dt(r.get("published_at")),
                is_processed=r.get("is_processed", False),
                is_duplicate=r.get("is_duplicate", False),
                extracted_entities=r.get("extracted_entities", []),
                sentiment_score=r.get("sentiment_score"),
                anomaly_score=r.get("anomaly_score"),
                matched_keywords=r.get("matched_keywords", []),
                metadata_=r.get("metadata_", {}),
            )
            session.merge(event)

            # Create entity_event link if we have a person reference
            if person_entity_id:
                entity_event_records.append({
                    "id": str(uuid.uuid4()),
                    "entity_id": person_entity_id,
                    "event_id": r["id"],
                    "role": "mentioned",
                })
        session.flush()

    # Bulk insert entity_events
    log(f"   Creating {len(entity_event_records)} entity↔event links...")
    entity_ids = {r["entity_id"] for r in entity_event_records}
    event_ids = {r["event_id"] for r in entity_event_records}
    
    existing_links = set()
    if entity_event_records:
        existing_rows = (
            session.query(EntityEvent.entity_id, EntityEvent.event_id)
            .filter(EntityEvent.entity_id.in_(list(entity_ids)))
            .filter(EntityEvent.event_id.in_(list(event_ids)))
            .all()
        )
        existing_links = {(row[0], row[1]) for row in existing_rows}

    inserted_count = 0
    for i in range(0, len(entity_event_records), BATCH_SIZE):
        batch = entity_event_records[i : i + BATCH_SIZE]
        for r in batch:
            if (r["entity_id"], r["event_id"]) in existing_links:
                continue
            
            ee = EntityEvent(
                id=r["id"],
                entity_id=r["entity_id"],
                event_id=r["event_id"],
                role=r["role"],
            )
            session.merge(ee)
            inserted_count += 1
        session.flush()

    log(f"   ✓ {len(records)} events loaded + {inserted_count} new entity-event links created")



def parse_dt(s):
    """Parse ISO datetime string, return None if falsy."""
    if not s:
        return None
    return datetime.fromisoformat(s.replace("Z", "+00:00"))


def log(msg: str):
    """Simple timestamped logger."""
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    try:
        print(f"[{ts}] {msg}")
    except UnicodeEncodeError:
        encoding = sys.stdout.encoding or 'ascii'
        safe_msg = msg.encode(encoding, errors='replace').decode(encoding)
        print(f"[{ts}] {safe_msg}")


def batch_insert(session, model, records: list, batch_size: int = BATCH_SIZE):
    """Insert records in batches, return count inserted."""
    total = 0
    for i in range(0, len(records), batch_size):
        batch = records[i : i + batch_size]
        session.bulk_save_objects([model(**r) for r in batch])
        session.flush()
        total += len(batch)
    return total


